window.generateProducts = function(seriesId, seriesName) {
  var series = window.getSeriesById(seriesId);
  var products = [];
  var total = series.productCount;
  var allSeriesImgs = series.productImages || [];

  for (var i = 1; i <= total; i++) {
    var num = i < 10 ? '0' + i : '' + i;
    var imgSrc = allSeriesImgs[i - 1];
    // Look up the per-item entry by exact id (products[] may be partial or out of order,
    // e.g. phytoncide only defines p05/p06)
    var expectId = seriesId + '-p' + num;
    var item = null;
    if (series.products) {
      for (var k = 0; k < series.products.length; k++) {
        if (series.products[k] && series.products[k].id === expectId) { item = series.products[k]; break; }
      }
    }

    // Real product name: per-item name (now synced English), list productNames, then generic fallback
    var itemName = null;
    if (item && item.name && item.name.indexOf('\u5355\u54c1') === -1) {
      itemName = item.name;
    }
    if (!itemName && series.productNames && series.productNames[i - 1]) {
      itemName = series.productNames[i - 1];
    }
    if (!itemName) itemName = seriesName + ' - Product ' + num;

    // Gallery: per-item override, else up to 4 sibling product images (main image is added by the page)
    var fallbackGallery = allSeriesImgs.filter(function(_, idx) { return idx !== (i - 1); }).slice(0, 4);
    var itemGallery = (item && item.gallery && item.gallery.length) ? item.gallery : fallbackGallery;

    // Detail blocks: per-item override, else sibling images
    var fallbackDetail = allSeriesImgs.filter(function(_, idx) { return idx !== (i - 1); }).slice(0, 10);
    var itemDetail = (item && item.detail && item.detail.length) ? item.detail : fallbackDetail;

    // Feature bullets: per-item override, else generic
    if (window.PRODUCT_SPECS && window.PRODUCT_SPECS[expectId] && window.PRODUCT_SPECS[expectId].feat && window.PRODUCT_SPECS[expectId].feat.length) itemFeatures = window.PRODUCT_SPECS[expectId].feat;
    var itemFeatures = (item && item.features && item.features.length) ? item.features : [
      "Provides intensive hydration",
      "Moisturizes, soothes and purifies for a dewy, clear complexion",
      "Improves unstable, troubled skin",
      "Private label & OEM available"
    ];

    var price = (window.getProductPricing ? window.getProductPricing(seriesId, i) : { priceMin: '3.50', priceMax: '8.50', moq: '500 pcs' });

    products.push({
      id: seriesId + '-p' + num,
      sku: 'LHX-' + seriesId.toUpperCase().replace(/-/g, '') + '-' + num,
      name: itemName,
      shortName: itemName,
      number: num,
      series: seriesName,
      seriesId: seriesId,
      image: imgSrc,
      gallery: itemGallery,
      detail: itemDetail,
      features: itemFeatures,
      ingredients: (window.PRODUCT_SPECS && window.PRODUCT_SPECS[seriesId + '-p' + num] || {}).ing || '',
      functions: (window.PRODUCT_SPECS && window.PRODUCT_SPECS[seriesId + '-p' + num] || {}).fn || '',
      priceMin: price.priceMin,
      priceMax: price.priceMax,
      moq: price.moq,
      tiers: price.tiers || null,
      description: 'High-quality ' + itemName + ' \u2014 premium formulation with Korean cosmetic technology, private label & OEM/ODM available.'
    });
  }
  return products;
};

window.getSeriesById = function(id) {
  for (var i = 0; i < window.PRODUCT_SERIES.length; i++) {
    if (window.PRODUCT_SERIES[i].id === id) return window.PRODUCT_SERIES[i];
  }
  return null;
};

window.getProductById = function(productId) {
  // productId format: seriesId-pXX
  var parts = productId.split('-p');
  if (parts.length < 2) return null;
  var seriesId = parts[0];
  var series = window.getSeriesById(seriesId);
  if (!series) return null;
  if (!series.productList) series.productList = window.generateProducts(seriesId, series.name);
  for (var i = 0; i < series.productList.length; i++) {
    if (series.productList[i].id === productId) {
      series.productList[i].seriesData = series;
      return series.productList[i];
    }
  }
  return null;
};

// Simple URL query parser
window.getQueryParam = function(name) {
  var params = new URLSearchParams(window.location.search);
  return params.get(name) ? params.get(name).trim() : null;
};
